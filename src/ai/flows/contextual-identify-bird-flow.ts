
'use server';
/**
 * @fileOverview An AI flow for identifying bird species from audio recordings.
 *
 * - identifyBirdBySound - A function that analyzes an audio recording to identify a bird.
 * - IdentifyBirdInput - The input type for the identifyBirdBySound function.
 * - IdentifyBirdOutput - The return type for the identifyBirdBySound function.
 */

import { ai } from '@/ai/genkit';
import { z } from 'zod';
import { getStorage } from 'firebase-admin/storage';
import wavDecoder from 'wav-decoder';
import { doc, getDoc } from 'firebase/firestore';
import { db } from '@/lib/firebase';
import type { AppAIVersion, PromptVersion, PromptContent } from '@/lib/types';
import { getActiveAIConfig } from '@/lib/actions';

const IdentifyBirdInputSchema = z.object({
  audioDataUri: z
    .string()
    .optional()
    .describe(
      "A recording of a bird song, as a data URI that must include a MIME type and use Base64 encoding. Expected format: 'data:<mimetype>;base64,<encoded_data>'"
    ),
    audioStoragePath: z.string().optional().describe('The path to an audio file in Firebase Storage. If provided, this is used instead of audioDataUri.'),
    timestamp: z.string().describe('The UTC timestamp of when the recording was made, in ISO 8601 format.'),
    latitude: z.number().optional().describe('The latitude of where the recording was made.'),
    longitude: z.number().optional().describe('The longitude of where the recording was made.'),
    locationDescription: z.string().optional().describe('A user-provided text description of the location (e.g., postcode, city, national park name).'),
    mode: z.enum(['newbie', 'twitcher']).describe('The application mode selected by the user, which may determine the expected audio quality and analysis depth.'),
    habitatPhotoDataUri: z.string().optional().describe("An optional photo of the bird's habitat, as a data URI."),
    habitatDescription: z.string().optional().describe("A user-provided text description of the habitat."),
    isDeveloperData: z.boolean().optional().describe("A flag to indicate if this is a developer test run, which might use a different AI version."),
});
export type IdentifyBirdInput = z.infer<typeof IdentifyBirdInputSchema>;

const IdentifyBirdOutputSchema = z.object({
  isBirdSong: z.boolean().describe('Whether or not the audio is believed to contain a bird song.'),
  commonName: z.string().optional().describe("The common name of the identified bird (e.g., 'American Robin')."),
  scientificName: z.string().optional().describe("The scientific name of the identified bird (e.g., 'Turdus migratorius')."),
  family: z.string().optional().describe("The taxonomic family of the bird (e.g., 'Psittacidae' for parrots)."),
  order: z.string().optional().describe("The taxonomic order of the bird (e.g., 'Passeriformes' for perching birds)."),
  description: z.string().optional().describe('A brief, interesting fact or description about the bird.'),
  imagePrompt: z.string().optional().describe('A simple, descriptive prompt for a text-to-image model to generate a picture of the bird (e.g., "photo of an American Robin on a branch").'),
  confidence: z.number().optional().describe('A number between 0 and 1 representing the AI\'s confidence in the identification.'),
  season: z.string().optional().describe("The season at the location of the recording (e.g., 'Summer', 'Winter')."),
  weather: z.string().optional().describe("A brief summary of the weather conditions (eg., 'Clear, 15°C, light breeze')."),
  aiGeneratedHabitatTags: z.array(z.string()).optional().describe('A list of structured tags describing the habitat, generated by the AI based on its analysis of all available habitat information.'),
  duration: z.number().optional().describe('The duration of the audio in seconds.'),
  promptVersion: z.string().optional().describe('The version of the prompt system used for this analysis.'),
});
export type IdentifyBirdOutput = z.infer<typeof IdentifyBirdOutputSchema>;

const DEFAULT_BIRD_PROMPT = `You are an expert ornithologist. Your primary goal is to identify bird species from audio recordings. The user will provide an audio file and optional location data. You MUST analyze this audio to determine if a bird song is present. If it is, identify the bird's common name, scientific name, taxonomic family, and order. If no bird song is discernible, you MUST set 'isBirdSong' to false. You must also generate a simple, descriptive prompt for a text-to-image model to create a photorealistic image of the identified bird.`;


const getCurrentWeather = ai.defineTool(
    {
      name: 'getCurrentWeather',
      description: 'Gets the historical weather for a given location and timestamp.',
      inputSchema: z.object({
        latitude: z.number(),
        longitude: z.number(),
        date: z.string().describe('The date in ISO 8601 format (YYYY-MM-DD).'),
      }),
      outputSchema: z.object({
        season: z.string(),
        temperature_celsius: z.number(),
        precipitation_mm: z.number(),
        wind_speed_kmh: z.number(),
        conditions: z.string(),
      }),
    },
    async ({ latitude, date }) => {
      // In a real app, this would call a weather API.
      // For now, we simulate it based on latitude and date to demonstrate the tool's functionality.
      const month = new Date(date).getMonth() + 1;
      const isNorthernHemisphere = latitude > 0;
  
      let season = 'Spring';
      if (month >= 3 && month <= 5) season = isNorthernHemisphere ? 'Spring' : 'Autumn';
      if (month >= 6 && month <= 8) season = isNorthernHemisphere ? 'Summer' : 'Winter';
      if (month >= 9 && month <= 11) season = isNorthernHemisphere ? 'Autumn' : 'Spring';
      if (month === 12 || month <= 2) season = isNorthernHemisphere ? 'Winter' : 'Summer';
  
      // Simulate some weather variations
      const temp = Math.floor(Math.random() * 20) + (season === 'Summer' ? 15 : 5);
      const precip = Math.random() > 0.8 ? Math.random() * 10 : 0;
      const wind = Math.random() * 20;
  
      return {
        season,
        temperature_celsius: parseFloat(temp.toFixed(1)),
        precipitation_mm: parseFloat(precip.toFixed(1)),
        wind_speed_kmh: parseFloat(wind.toFixed(1)),
        conditions: precip > 0 ? 'Rainy' : 'Clear',
      };
    }
  );

/**
 * Downloads a file from Firebase Storage, converts it to a Base64 data URI,
 * and calculates its duration. This runs on the server.
 * @returns An object with the data URI and the duration in seconds.
 */
async function fileToDataUriWithDuration(storagePath: string): Promise<{ dataUri: string; duration: number | undefined }> {
    const bucket = getStorage().bucket();
    const file = bucket.file(storagePath);
    const [metadata] = await file.getMetadata();
    const mimeType = metadata.contentType || 'application/octet-stream';

    // Create a readable stream from the file
    const stream = file.createReadStream();

    // Read the stream into a buffer
    const chunks: Buffer[] = [];
    for await (const chunk of stream) {
        chunks.push(chunk);
    }
    const buffer = Buffer.concat(chunks);

    // Calculate duration for WAV files
    let duration: number | undefined;
    if (mimeType === 'audio/wav' || storagePath.endsWith('.wav')) {
        try {
            const decoded = await wavDecoder.decode(buffer);
            duration = decoded.duration;
        } catch (e) {
            console.warn(`Could not decode WAV file to get duration: ${storagePath}`, e);
        }
    }
    // Note: Duration calculation for other formats like webm/opus would require a library like 'music-metadata'.
    // For now, we only support WAV duration on the server.

    // Convert buffer to Base64 and format as a data URI
    const base64 = buffer.toString('base64');
    const dataUri = `data:${mimeType};base64,${base64}`;

    return { dataUri, duration };
}


export async function identifyBirdBySound(
  input: IdentifyBirdInput
): Promise<IdentifyBirdOutput> {
  let duration: number | undefined;

  // If a storage path is provided, download the file from the server,
  // convert it to a data URI, and get its duration.
  if (input.audioStoragePath && !input.audioDataUri) {
      const { dataUri, duration: fileDuration } = await fileToDataUriWithDuration(input.audioStoragePath);
      input.audioDataUri = dataUri;
      duration = fileDuration;
  }
  
  if (!input.audioDataUri) {
      throw new Error("No audio data provided. Please provide either 'audioDataUri' or 'audioStoragePath'.");
  }
  
  const result = await identifyBirdFlow(input);
  
  // Add the server-calculated duration to the final result if it exists.
  if (duration && result.duration === undefined) {
    result.duration = duration;
  }

  return result;
}


const identifyBirdFlow = ai.defineFlow(
  {
    name: 'identifyBirdFlow',
    inputSchema: IdentifyBirdInputSchema,
    outputSchema: IdentifyBirdOutputSchema,
    config: {
      retries: 3,
    },
  },
  async (input) => {
    const flowInput = input;
    const systemId = 'bird-identifier-ai-newbie';

    let promptText = DEFAULT_BIRD_PROMPT;
    let promptVersion = 'v1.0.0-default';

    const appConfig = await getActiveAIConfig();

    if (appConfig) {
      const activeAppVersionId = input.isDeveloperData ? appConfig.developmentAppAIVersion : appConfig.activeAppAIVersion;
      
      if (activeAppVersionId) {
        const appVersionDoc = await getDoc(doc(db, 'app_ai_versions', activeAppVersionId));

        if (appVersionDoc.exists()) {
          const appVersionData = appVersionDoc.data() as AppAIVersion;
          const systemVersionId = appVersionData.systems[systemId];

          if (systemVersionId) {
            const versionDoc = await getDoc(doc(db, 'prompt_versions', systemVersionId));
            if (versionDoc.exists()) {
              const versionData = versionDoc.data() as PromptVersion;
              promptVersion = versionData.version;

              const contentId = versionData.composedPrompts['base_instruction'];
              if (contentId) {
                const contentDoc = await getDoc(doc(db, 'prompt_content', contentId));
                if (contentDoc.exists()) {
                  promptText = (contentDoc.data() as PromptContent).promptText;
                }
              }
            }
          }
        }
      }
    }

    const identifyBirdPrompt = ai.definePrompt({
        name: 'identifyBirdPrompt',
        prompt: promptText,
        input: { schema: IdentifyBirdInputSchema },
        output: { schema: IdentifyBirdOutputSchema },
        tools: [getCurrentWeather],
    });

    const { output } = await identifyBirdPrompt(flowInput);

    if (!output) {
      throw new Error('The model failed to return a valid analysis.');
    }
    
    output.promptVersion = promptVersion;

    // If no bird song was detected, fill in placeholder text.
    if (output.isBirdSong === false) {
        return {
            ...output,
            isBirdSong: false,
            commonName: "Not identified",
            scientificName: "Not identified",
            family: "Not identified",
            order: "Not identified",
            description: "The AI did not detect a bird song in this audio recording. You can review it later in the Mystery Recordings log.",
            imagePrompt: "photo of a question mark in a forest",
            confidence: 0,
            season: output.season || "Unknown",
            weather: output.weather || "Unknown",
aiGeneratedHabitatTags: [],
            duration: output.duration,
            promptVersion: output.promptVersion,
        };
    }
    
    return output;
  }
);
